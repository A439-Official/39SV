function toHex(s)
    local parts = {}
    for i = 1, #s do
        parts[i] = string.format("%04X", string.byte(s, i))
    end
    return table.concat(parts, "|")
end

function fromHex(s)
    local result = {}
    for hex in s:gmatch("[^|]+") do
        table.insert(result, string.char(tonumber(hex, 16)))
    end
    return table.concat(result)
end

