        for line in data:gmatch("[^\r\n]+") do
            local t, m = line:match("^(%S+)%s+(%S+)$")
            if t and m then
                table.insert(svs, {
                    time = tonumber(t) or 0,
                    multiplier = tonumber(m) or 1
                })
            end
        end
    end
    vars.copiedSVs = svs
    return svs
end

